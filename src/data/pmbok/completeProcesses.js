// プロセス数の検証
export function validateProcessCount() {
  let totalProcesses = 0
  completeKnowledgeAreas.forEach((area) => {
    const areaProcesses = completeProcesses[area.id]
    let count = 0
    if (areaProcesses) {
      Object.values(areaProcesses).forEach((groupProcesses) => {
        count += groupProcesses.length
      })
    }
    if (count !== area.processes) {
      console.warn(`⚠️ ${area.name}: Expected ${area.processes} processes, got ${count}`)
    }
    totalProcesses += count
  })

  return {
    total: totalProcesses,
    expected: 49,
    isValid: totalProcesses === 49,
  }
}

// エクスポート関数
export function getAllProcesses() {
  const allProcesses = []
  Object.keys(completeProcesses).forEach((areaId) => {
    const area = completeKnowledgeAreas.find((ka) => ka.id === areaId)
    Object.keys(completeProcesses[areaId]).forEach((group) => {
      completeProcesses[areaId][group].forEach((process) => {
        allProcesses.push({
          name: process,
          knowledgeArea: area.name,
          processGroup: group,
          itto: processITTO[process] || {},
        })
      })
    })
  })
  return allProcesses
}
